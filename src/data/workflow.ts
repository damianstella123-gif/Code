import { addDaysISO } from '@/lib/format'

export type FaseStato = 'bloccata' | 'in_attesa' | 'in_corso' | 'completata' | 'critica'

export type LogTipo = 'avanzamento' | 'blocco' | 'commento' | 'sistema' | 'alert'

export interface LogEntry {
  id: string
  tipo: LogTipo
  testo: string
  autoreId: string
  data: string
}

export interface WorkflowFase {
  id: string
  ordine: number
  nome: string
  descrizione: string
  stato: FaseStato
  responsabileId: string
  taskIds: string[]
  taskCriticiIds: string[]   // task che bloccano l'avanzamento se non completati
  deadline: string
  avanzamento: number        // 0-100
  log: LogEntry[]
  fornitoriIds: string[]
  note: string
}

export interface EventoWorkflow {
  id: string
  eventoId: string
  faseCorrenteOrdine: number
  fasi: WorkflowFase[]
  creatoIl: string
  aggiornatoIl: string
}

